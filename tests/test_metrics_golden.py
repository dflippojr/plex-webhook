"""/metrics output for a fixed sequence of events stays what master produced (#185).

tests/golden/metrics.txt was generated by tests/metrics_script.py on master before the
composition-root refactor. Values that differ between runs (process and GC figures,
the last-event timestamp, the _created timestamps) are masked; every family, HELP and
TYPE line, label set, sample value and their order must match.
"""
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "tests" / "golden" / "metrics.txt"


def test_metrics_output_matches_master_for_the_scripted_events(tmp_path):
    env = {**os.environ, "PYTHONPATH": str(ROOT)}
    out = subprocess.run([sys.executable, str(ROOT / "tests" / "metrics_script.py"), str(tmp_path)],
                         env=env, cwd=tmp_path, capture_output=True, text=True, timeout=120)
    assert out.returncode == 0, out.stderr[-2000:]
    assert out.stdout == GOLDEN.read_text(encoding="utf-8")
